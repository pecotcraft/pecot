"""Gitlint custom rule: Require Japanese in commit message title."""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, cast

from gitlint.options import BoolOption
from gitlint.rules import CommitRule, RuleViolation

if TYPE_CHECKING:
    from gitlint.git import GitCommit


class TitleRequiresJapanese(CommitRule):
    """Enforce that commit message title contains Japanese characters.

    This rule checks that the description part of the commit message
    (after the Conventional Commits prefix) contains at least one
    Japanese character (hiragana, katakana, or kanji).
    """

    name = "title-requires-japanese"
    id = "UC1"

    options_spec = [
        BoolOption(
            "allow-revert",
            True,
            "Allow revert commits without Japanese (auto-generated messages)",
        ),
        BoolOption(
            "allow-release",
            True,
            "Allow release commits without Japanese (auto-generated by nx release)",
        ),
    ]

    # Japanese character ranges:
    # - Hiragana: ぀-ゟ
    # - Katakana: ゠-ヿ
    # - Kanji (CJK Unified Ideographs): 一-鿿
    JAPANESE_PATTERN = re.compile(r"[぀-ゟ゠-ヿ一-鿿]")

    # Conventional Commits prefix pattern: type(scope): or type:
    CONVENTIONAL_PREFIX = re.compile(r"^[a-z]+(\([^)]+\))?!?:\s*")

    # Release commit prefix (auto-generated by nx release). Matches the same
    # convention as the pre-push version-plan guard's RELEASE_RE.
    RELEASE_PREFIX = re.compile(r"^chore\(release\)!?:")

    def validate(self, commit: GitCommit) -> list[RuleViolation] | None:
        """Validate that the commit title contains Japanese characters."""
        # commit.message は gitlint 基底が完全 untyped のため Unknown を返す。
        # cast で str に型固定し、以降の re 呼び出しのカスケードを断つ。
        title: str = cast(str, commit.message.title)  # pyright: ignore[reportUnknownMemberType]
        # options も gitlint 基底が完全 untyped のため dict[Unknown, Unknown]。
        # cast で具体型に固定し、以降の .value アクセスのカスケードを断つ。
        opts = cast(dict[str, BoolOption], self.options)  # pyright: ignore[reportUnknownMemberType]

        # Skip revert commits if allowed (auto-generated by git revert)
        if opts["allow-revert"].value and title.startswith('Revert "'):
            return None

        # Skip release commits if allowed (auto-generated by nx release)
        if opts["allow-release"].value and self.RELEASE_PREFIX.match(title):
            return None

        # Remove Conventional Commits prefix to get the description
        match = self.CONVENTIONAL_PREFIX.match(title)
        if match:
            description = title[match.end() :]
        else:
            description = title

        # Check for Japanese characters
        if not self.JAPANESE_PATTERN.search(description):
            return [
                RuleViolation(
                    self.id,
                    "コミットメッセージの説明部分に日本語を含めてください。\n"
                    "理由: このプロジェクトではコミット履歴の可読性のため、"
                    "コミットメッセージを日本語で記述するルールです。\n"
                    "Conventional Commitsプレフィックス（type(scope):）の後に"
                    "日本語で記述します。\n"
                    "例: feat(hooks): フックメッセージを改善 / "
                    "fix(cli): バリデーションを修正",
                    line_nr=1,
                )
            ]

        return None
