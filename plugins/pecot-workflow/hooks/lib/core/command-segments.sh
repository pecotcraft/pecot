#!/bin/bash
# Bash コマンド文字列のクオート正規化・セグメント分割と、起動形のパターン（source して使う）。
# external-post-check.sh と pecot-cli-deny.sh が共有する。

# クオート正規化。空白を含むクオート span は丸ごと除去して、中の疑似コマンドを無効にする。
# 空白を含まないクオート（コマンドパス）は、クオートだけ外す。
_dequote() {
  printf '%s' "$1" \
    | sed "s/'[^']* [^']*'//g" \
    | sed 's/"[^"]* [^"]*"//g' \
    | tr -d "'\""
}

# セグメント先頭アンカー（区切りは含めない。先頭と任意の環境変数前置だけ）。
_SEG_ANCHOR='^[[:space:]]*([A-Z_]+=[^ ]*[[:space:]]+)*'
# gh 起動形: gh / フルパス(/…/gh)。
_GH='(/[^ ]*/)?gh'

# 区切り文字（; && || & | ` $( ( ) ）で分割し、改行区切りで出力する。
# && は & より先に、|| は | より先に置換する（2 文字の区切りを先に消費させる）。
_split_segments() {
  local s="$1"
  s=${s//&&/$'\n'}
  s=${s//&/$'\n'}
  s=${s//||/$'\n'}
  s=${s//;/$'\n'}
  s=${s//|/$'\n'}
  s=${s//\`/$'\n'}
  s=${s//\$(/$'\n'}
  s=${s//)/$'\n'}
  s=${s//(/$'\n'}
  printf '%s' "$s"
}
